/**
 * Strict Rule for Story Card Generation:
 * An active member can ONLY generate and share their OWN story card.
 * Nobody is allowed to generate another member's story card!
 */
export function canGenerateStoryCard(actor: Profile | null, targetMember: Profile): boolean {
  if (!actor) return false;
  return actor.id === targetMember.id;
}

/**
 * Checks if user can manage events for a specific committee scope
 * Sub-Head has full management rights alongside Head
 */
export function canManageEvent(actor: Profile, event?: EventItem): boolean {
  if (isTeamLeadership(actor.role)) return true;
  
  const isCommLeader = actor.role === 'head' || actor.role === 'sub_head';
  if (!isCommLeader) return false;

  if (!event) return true; // Can create event for own committee

  const actorComm = (actor.committee || actor.committee_key || '').toLowerCase();
  const eventComm = (event.committee_key || '').toLowerCase();

  // Can manage if event belongs to own committee or was created by actor
  if (event.created_by_id === actor.id) return true;
  if (eventComm === actorComm) return true;

  return false;
}

/**
 * Checks if user can review & approve/reject an applicant
 * Sub-Head has identical review and approval authority to Head
 */
export function canReviewApplication(
  actor: Profile, 
  application: Application
): { canDecideAsIR: boolean; canDecideAsHead: boolean; canOverrideAsOG: boolean } {
  const isOGUser = actor.role === 'og';
  const isTeamLead = isTeamLeadership(actor.role);
  const isIR = isIREvaluator(actor) || isIRLeadership(actor);

  const actorComm = (actor.committee || actor.committee_key || '').toLowerCase();
  const appComm = (application.committee_key || '').toLowerCase();
  const isCommLeader = (actor.role === 'head' || actor.role === 'sub_head') && actorComm === appComm;

  return {
    canDecideAsIR: isIR || isTeamLead || isOGUser,
    canDecideAsHead: isCommLeader || isTeamLead || isOGUser,
    canOverrideAsOG: isOGUser || isTeamLead
  };
}

/**
 * Checks if user can manage recruitment questions in a given category
 * Sub-Head has identical question management rights
 */
export function canManageQuestions(
  actor: Profile, 
  category: QuestionCategory, 
  targetCommitteeKey?: CommitteeKey
): boolean {
  if (isTeamLeadership(actor.role)) return true;

  if (category === 'global') {
    return isTeamLeadership(actor.role);
  }

  if (category === 'ir') {
    return isIRLeadership(actor) || (actor.role === 'ir' && actor.is_board_member);
  }

  if (category === 'committee' && targetCommitteeKey) {
    const isCommLeader = actor.role === 'head' || actor.role === 'sub_head';
    const actorComm = (actor.committee || actor.committee_key || '').toLowerCase();
    return isCommLeader && actorComm === targetCommitteeKey.toLowerCase();
  }

  return false;
}

/**
 * Checks if user has permission to access the Data Analytics & Export Hub
 */
export function canAccessDataAnalytics(actor: Profile | null): boolean {
  if (!actor) return false;
  if (isTeamLeadership(actor.role)) return true;
  if (isIRLeadership(actor)) return true;
  if (actor.role === 'head' || actor.role === 'sub_head') return true;
  
  // Data analysis / Secretary specialists
  const comm = (actor.committee || actor.committee_key || '').toLowerCase();
  const pos = (actor.position || '').toLowerCase();
  if (comm === 'secretary' || pos.includes('data') || pos.includes('analyst')) return true;

  return false;
}

